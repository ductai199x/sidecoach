"""Ship the desktop's mark to the app: the launcher icon, the splash and the notification.

The brand is the knight in `desktop/brand/logo.svg` (docs/app-plan.md, "The logo"): amber
#F2B441 with a navy #141A2A mane stroke and a camera-lens eye, traced by vtracer into seven
stacked paths. The desktop's icon set is that mark on a rounded tile a step lighter than
the navy (#212A45), so the mane shows. Android wants vectors rather than the desktop's
PNGs -- an adaptive icon is two layers the launcher masks to its own shape, and a
notification icon is a one-colour silhouette -- so this turns the same paths into
VectorDrawables, and the phone's mark is the desktop's by construction rather than by eye:

    drawable/ic_launcher_foreground.xml   the mark, full colour, in the adaptive safe zone
    drawable/ic_launcher_monochrome.xml   the knight's silhouette, for themed icons
    drawable/ic_stat_capture.xml          the silhouette, white, for the status bar

The tile colour is `ic_launcher_background` in values/colors.xml. Run it again whenever
the logo changes:

    uv run --no-sync python D:/sidecoach-android/tools/sync_brand.py
"""

from __future__ import annotations

import re
from pathlib import Path

DESKTOP = Path("D:/chess-coaching-companion")
LOGO = DESKTOP / "desktop" / "brand" / "logo.svg"
RES = Path(__file__).resolve().parent.parent / "app" / "src" / "main" / "res" / "drawable"

AMBER = "#F2B441"

PATH = re.compile(
    r'<path d="(?P<d>[^"]*)"[^>]*fill="(?P<fill>[^"]*)"[^>]*'
    r'transform="translate\((?P<tx>[-\d.]+),(?P<ty>[-\d.]+)\)"'
)
NUMBER = re.compile(r"-?\d+(?:\.\d+)?(?:e-?\d+)?")


def paths() -> tuple[tuple[float, float, float, float], list[tuple[str, str]]]:
    """The viewBox, and each path as (fill, pathData) with its translate baked in.

    vtracer writes only absolute M, C and Z, every number a coordinate in x, y pairs, so
    baking a translate is adding it to every pair."""
    svg = LOGO.read_text(encoding="utf-8")
    box = re.search(r'viewBox="([^"]*)"', svg)
    assert box, "the logo has no viewBox"
    vx, vy, vw, vh = (float(v) for v in box.group(1).split())
    out: list[tuple[str, str]] = []
    for match in PATH.finditer(svg):
        d = match.group("d")
        assert set(re.findall(r"[A-Za-z]", d)) <= {"M", "C", "Z"}, "a command vtracer did not write"
        tx, ty = float(match.group("tx")), float(match.group("ty"))
        baked: list[str] = []
        for token in re.findall(r"[MCZ]|[^MCZ]+", d):
            if token in "MCZ":
                baked.append(token)
                continue
            values = [float(n) for n in NUMBER.findall(token)]
            assert len(values) % 2 == 0, "an odd count of coordinates"
            pairs = [
                f"{_num(values[i] + tx)},{_num(values[i + 1] + ty)}"
                for i in range(0, len(values), 2)
            ]
            baked.append(" ".join(pairs))
        out.append((match.group("fill").upper(), " ".join(baked).replace(" Z", "Z")))
    assert len(out) == 7, f"expected the logo's seven paths, found {len(out)}"
    return (vx, vy, vw, vh), out


def _num(value: float) -> str:
    return f"{value:.2f}".rstrip("0").rstrip(".")


def vector(
    name: str,
    size: float,
    height: float,
    layers: list[tuple[str, str, str]],
    box: tuple[float, float, float, float],
    *,
    tint: str | None = None,
    note: str,
) -> None:
    """A square VectorDrawable `size` units across with the mark `height` tall, centred."""
    vx, vy, vw, vh = box
    scale = height / vh
    left = (size - vw * scale) / 2
    top = (size - height) / 2
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {note} Generated by tools/sync_brand.py from desktop/brand/logo.svg. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{_num(size)}dp"',
        f'    android:height="{_num(size)}dp"',
        f'    android:viewportWidth="{_num(size)}"',
        f'    android:viewportHeight="{_num(size)}"' + (">" if tint is None else ""),
    ]
    if tint is not None:
        lines.append(f'    android:tint="{tint}">')
    lines += [
        "    <group",
        f'        android:scaleX="{scale:.6f}"',
        f'        android:scaleY="{scale:.6f}"',
        f'        android:translateX="{left - vx * scale:.4f}"',
        f'        android:translateY="{top - vy * scale:.4f}">',
    ]
    for fill, data, rule in layers:
        lines += [
            "        <path",
            f'            android:fillColor="{fill}"',
            *([f'            android:fillType="{rule}"'] if rule != "nonZero" else []),
            f'            android:pathData="{data}" />',
        ]
    lines += ["    </group>", "</vector>", ""]
    (RES / f"{name}.xml").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote drawable/{name}.xml ({len(layers)} paths)")


def main() -> None:
    box, layers = paths()
    # The stack, as vtracer drew it: the head and neck, the lower base step, the mane, the
    # upper base step, then the eye -- a navy lens, an amber ring on it, a navy pupil.
    full = [(fill, data, "nonZero") for fill, data in layers]
    head, lower, _mane, upper, lens, ring, pupil = (data for _, data in layers)
    # One colour: the amber shapes, the eye cut through the head -- lens out, ring back
    # in, pupil out again, which is what even-odd filling of the four nested outlines does.
    silhouette = [
        ("#FFFFFF", " ".join([head, lens, ring, pupil]), "evenOdd"),
        ("#FFFFFF", lower, "nonZero"),
        ("#FFFFFF", upper, "nonZero"),
    ]

    # An adaptive icon is 108 dp, of which the launcher shows about the middle 72 and keeps
    # a 66 dp circle whatever its mask. The desktop's tile holds the mark at 77% of its
    # height; 55 dp is that share of the visible 72, and its corners stay in the circle.
    vector(
        "ic_launcher_foreground", 108, 55, full, box,
        note="The launcher icon's mark, on the tile colour ic_launcher_background.",
    )
    vector(
        "ic_launcher_monochrome", 108, 55, silhouette, box,
        note="The knight in one colour, for the launcher's themed icons.",
    )
    # A status-bar icon is white on transparent, 24 dp with a couple of dp of air.
    vector(
        "ic_stat_capture", 24, 20, silhouette, box, tint="#FFFFFF",
        note="The knight, white, for the capture's notification.",
    )
    assert AMBER in {fill for fill, _ in layers}


if __name__ == "__main__":
    main()
