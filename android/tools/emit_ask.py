"""Write the texts of `profile/ask.py` into `profile/AskText.kt`, one literal per line.

The schema in words, the worked queries and the system message are what the coach's model
is given to write its own SQL; the phone must give it the same words, byte for byte. They
are written as one Kotlin literal per line joined with "\\n", never a raw string: this
checkout is `text=auto`, and a raw string would carry CRLF into the prompt. Run it again
whenever ask.py changes:

    cd D:/chess-coaching-companion
    uv run --no-sync python android/tools/emit_ask.py
"""

from __future__ import annotations

import sys
from pathlib import Path

DESKTOP = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(DESKTOP / "src"))

from sidecoach.profile.ask import EXAMPLES, SCHEMA_DOC, SYSTEM  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "app" / "src" / "main" / "java" / "com" / "sidecoach" / "profile" / "AskText.kt"


def literal(text: str) -> str:
    out = text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    return f'"{out}"'


def lines(name: str, text: str) -> str:
    body = ",\n".join(f"    {literal(line)}" for line in text.split("\n"))
    return f"val {name}: String = listOf(\n{body},\n).joinToString(\"\\n\")\n"


def main() -> None:
    examples = ",\n".join(f"    {literal(q)} to\n        {literal(sql)}" for q, sql in EXAMPLES)
    text = (
        "package com.sidecoach.profile\n\n"
        "// Generated by tools/emit_ask.py from `sidecoach/profile/ask.py`: do not edit by hand.\n"
        "// One literal per line joined with \"\\n\", so a CRLF checkout cannot reach the prompt.\n\n"
        "/** The record in words: the tables, what each column means and its units. */\n"
        + lines("SCHEMA_DOC", SCHEMA_DOC)
        + "\n/** Worked queries: a question, and the SQL that answers it. */\n"
        + f"val EXAMPLES: List<Pair<String, String>> = listOf(\n{examples},\n)\n"
        + "\n/** The system message's template: {rounds}, {schema} and {examples} filled in. */\n"
        + lines("SYSTEM_TEMPLATE", SYSTEM)
    )
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(SCHEMA_DOC.splitlines())} schema lines, {len(EXAMPLES)} examples -> {OUT}")


if __name__ == "__main__":
    main()
